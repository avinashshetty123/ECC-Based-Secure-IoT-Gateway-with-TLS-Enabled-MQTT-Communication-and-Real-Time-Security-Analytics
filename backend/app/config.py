"""Central settings for every component.

Values come from environment variables / an optional .env file, with safe
local defaults. Secrets are loaded from config/secrets/credentials.json,
which is generated by scripts/setup_credentials.py and git-ignored.
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path

from dotenv import load_dotenv

ROOT = Path(__file__).resolve().parent.parent
load_dotenv(ROOT / ".env")

CONFIG_DIR = ROOT / "config"
SECRETS_FILE = CONFIG_DIR / "secrets" / "credentials.json"
CERT_DIR = ROOT / "certificates"
LOG_DIR = ROOT / os.getenv("LOG_DIR", "logs")
DB_PATH = ROOT / os.getenv("DB_PATH", "data/iot_gateway.db")
MOSQUITTO_DIR = Path(os.getenv("MOSQUITTO_DIR", r"C:\Program Files\mosquitto"))

MODES = ("plain", "tls", "mtls")

# Topic layout (see docs/ARCHITECTURE.md section 2)
TOPIC_INGEST = "ingest/{device_id}"
TOPIC_INGEST_ALL = "ingest/+"
TOPIC_TELEMETRY = "sensors/{device_id}/telemetry"
TOPIC_TELEMETRY_ALL = "sensors/+/telemetry"
TOPIC_GATEWAY_EVENTS = "gateway/events"


@dataclass(frozen=True)
class BrokerEndpoint:
    mode: str
    host: str
    port: int


def broker_endpoint(mode: str) -> BrokerEndpoint:
    if mode not in MODES:
        raise ValueError(f"Unknown mode {mode!r}; expected one of {MODES}")
    host = os.getenv("MQTT_HOST", "localhost")
    ports = {
        "plain": int(os.getenv("MQTT_PORT_PLAIN", "1884")),
        "tls": int(os.getenv("MQTT_PORT_TLS", "8883")),
        "mtls": int(os.getenv("MQTT_PORT_MTLS", "8884")),
    }
    return BrokerEndpoint(mode, host, ports[mode])


def device_ids(count: int) -> list[str]:
    return [f"dev-{i:03d}" for i in range(1, count + 1)]


def load_credentials() -> dict[str, str]:
    """Return {username: password}. Raises a helpful error if not generated yet."""
    if not SECRETS_FILE.exists():
        raise FileNotFoundError(
            f"{SECRETS_FILE} not found. Run: .venv\\Scripts\\python scripts\\setup_credentials.py"
        )
    return json.loads(SECRETS_FILE.read_text(encoding="utf-8"))


def password_for(username: str) -> str:
    creds = load_credentials()
    if username not in creds:
        raise KeyError(f"No credentials for {username!r}; re-run scripts/setup_credentials.py")
    return creds[username]
